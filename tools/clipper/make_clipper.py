#!/usr/bin/env python3
"""Turn the standalone Long to Shorts Clipper (tools/clipper/source.html) into a Toolsaku tool.

Writes:
  tools/clipper/app.html      the clipper's markup, dropped into #x-tool by tools/build.py
  assets/css/clipper.css      its styles, recoloured to the Toolsaku palette
  assets/js/clipper.js        its scripts (classic script, no modules)

Class names are renamed x-* -> lts-* (and data-i18n -> data-li18n) so they never clash with
the Toolsaku shell, which uses the same x- prefix. Run before tools/build.py.
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
src = open(os.path.join(HERE, "source.html"), encoding="utf-8").read()

def rename(t):
    t = re.sub(r"(?<![\w\-/])x-(?=[a-zA-Z])", "lts-", t)
    t = t.replace("--x-", "--lts-")
    t = t.replace("data-i18n", "data-li18n")
    return t

# ---- CSS -------------------------------------------------------------------------------
styles = re.findall(r"<style>(.*?)</style>", src, flags=re.S)
css = "\n".join(styles)
css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
css = re.sub(r"\n\s*body\s*\{[^}]*\}", "\n", css)
css = re.sub(r"\n\s*\.page\s*\{[^}]*\}", "\n", css)
css = css.replace("--hark-", "--base-")
COLORS = {
    "#7c5cff": "#2563FF", "#6d4aff": "#2563FF", "#ff4fa3": "#22D3EE", "#c2338f": "#0EA5C6",
    "#ff8a3d": "#38BDF8", "#e0561a": "#0E7490", "#2ee6d6": "#22D3EE", "#1a1440": "#0D1530",
    "#0d0b1f": "#0A0F1E", "#08080f": "#0A0F1E", "#111019": "#0D1530", "#16162a": "#0D1530",
    "#7c3aed": "#2563FF", "#ec4899": "#06B6D4",
}
for a, b in COLORS.items():
    css = re.sub(re.escape(a) + r"\b", b, css, flags=re.I)
RGB = {"124 92 255": "37 99 255", "194 51 143": "14 165 198", "255 79 163": "34 211 238",
       "255 138 61": "56 189 248", "22 21 34": "13 21 48", "8 8 15": "10 15 30", "46 230 214": "34 211 238"}
for a, b in RGB.items():
    css = css.replace("rgb(" + a + " /", "rgb(" + b + " /")
css = rename(css)
# Scope page-level rules to the tool so the Toolsaku page keeps its own background and header.
css = css.replace(":root {", "#x-tool {", 1)
css = css.replace(":root body .lts-hidden", "#x-tool .lts-hidden")
css += """
/* Toolsaku embedding */
#x-tool .lts-app { max-width: 720px; padding-top: 4px; }
#x-tool .lts-top h1 { font-size: 1.35rem; }
.lts-head, .lts-bg, .lts-more, .lts-foot { display: none !important; }
html[data-theme="light"] #x-tool .lts-boost { color-scheme: light; }
"""

# ---- Markup ----------------------------------------------------------------------------
body = src[src.index("<body"):]
a = body.index('<div class="x-app" id="tool">')
b = body.index("</main>", a)
app = body[a:b].rstrip()
app = app[: app.rstrip().rfind("</div>")] + "</div>"  # keep the app div itself
tail_a = body.index("</footer>")
tail_a = body.index("</div>", tail_a) + len("</div>")
tail_b = body.index('<script src="hark.js">')
tail = body[tail_a:tail_b]
tail = re.sub(r"<script\b.*?</script>", "", tail, flags=re.S)
markup = app + "\n" + tail.strip() + "\n"
markup = re.sub(r'<button class="x-btn x-inst"[^>]*>.*?</button>', "", markup, flags=re.S)
markup = rename(markup)

# ---- JS --------------------------------------------------------------------------------
scripts = re.findall(r"<script>(.*?)</script>", src[src.index("</style>"):], flags=re.S)
scripts = [s for s in scripts if "application/ld+json" not in s and s.strip()]
js = "\n;\n".join(scripts)
js = re.sub(r'if \("serviceWorker" in navigator[^\n]*\n[^\n]*serviceWorker\.register[^\n]*\n\s*\}', "/* no service worker inside Toolsaku */", js)
js = js.replace("document.documentElement.lang = lang", "void 0")
js = rename(js)
js = ("/* Long to Shorts Clipper, embedded in Toolsaku. Generated by tools/clipper/make_clipper.py: edit source.html, not this file. */\n"
      + js + """
;
/* Follow the Toolsaku language picker: Hindi -> Hindi UI, anything else -> English. */
(function () {
  function sync(l) { if (window.L10N) window.L10N.setLang(l === "hi" ? "hi" : "en"); }
  window.addEventListener("i18n:change", function (e) { sync(e.detail && e.detail.lang); });
  try { var s = localStorage.getItem("sugoi-lang"); if (s && !localStorage.getItem("lts-lang")) sync(s); } catch (e) {}
})();
""")

open(os.path.join(HERE, "app.html"), "w", encoding="utf-8").write(markup)
open(os.path.join(ROOT, "assets/css/clipper.css"), "w", encoding="utf-8").write(css.strip() + "\n")
open(os.path.join(ROOT, "assets/js/clipper.js"), "w", encoding="utf-8").write(js)
print("clipper: markup %d B, css %d B, js %d B, scripts %d" % (len(markup), len(css), len(js), len(scripts)))
